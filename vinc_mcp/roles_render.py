def _fence(body: str) -> str:
    """본문을 백틱 울타리에 넣는다. 울타리는 **본문 안의 어떤 백틱 연속보다 길게**
    잡는다(CommonMark 규칙) — 역할 껍데기는 이미 ``` 블록을 품고 있어서, 고정
    3백틱이면 그 안쪽에서 울타리가 닫히고 뒤쪽 텍스트가 데이터 경계 밖으로 새어
    나온다. 결정론이라 테스트가 바이트로 고정할 수 있다."""
    longest = max((len(m) for m in re.findall(r"`+", body)), default=0)
    tick = "`" * max(3, longest + 1)
    return f"{tick}\n{body}\n{tick}"
