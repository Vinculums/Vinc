# ── 스냅샷 모양 ───────────────────────────────────────────────────────────────

def _order(value):
    """dict 는 키 정렬, list 는 **그대로**. 목록의 순서가 뜻을 담기 때문이다 —
    `reads` 는 '이 순서로 읽어라'이고, 정렬하면 그 지시가 사라진다."""
    if isinstance(value, dict):
        return {k: _order(value[k]) for k in sorted(value)}
    if isinstance(value, list):
        return [_order(v) for v in value]
    return value


_NOTE = ("generated by scripts/agents_sync.py --pull from the agent topics (agent, vinc/agent) — "
         "do not hand edit. --gen renders agents/shells/*.md from this; "
         "--check compares them offline. The graph is canonical.")


_LABEL_PREFIX = "Agent role: "


def works_with(rid: str, nodes: list[dict], edges: list[dict]) -> dict:
    """역할 사이 엣지 → 넘겨주는 곳·받는 곳·옆에서 같이 일하는 곳.

    협업의 정본은 엣지다(props 에 사본을 두면 한쪽만 고쳐진다). `--pull` 과
    `prompts/get` 이 둘 다 `vinc_graph` 깊이 1 응답을 들고 있으므로 **이 함수 하나**를
    지나면 두 표면이 같은 줄을 낸다. prerequisite_of 는 방향이 뜻이다: A→B 면 A 의 일이
    B 에 앞선다(A 가 넘긴다). relates_to 는 방향이 없다."""
    titles = {n.get("id"): str(n.get("label") or n.get("title") or "") for n in nodes}

    def show(other: str) -> str:
        title = titles.get(other, "").removeprefix(_LABEL_PREFIX)
        slug = other.split(":", 1)[1]
        return f"{slug} ({title})" if title else slug

    out: dict[str, set[str]] = {"hands_to": set(), "receives_from": set(),
                                "works_beside": set(), "returns_to": set(),
                                "receives_returns_from": set()}
    for e in edges or []:
        src, dst = str(e.get("source") or ""), str(e.get("target") or "")
        if rid not in (src, dst) or src == dst or not (is_role_id(src) and is_role_id(dst)):
            continue
        other = dst if src == rid else src
        kind = str(e.get("type") or "").upper()
        if kind == "PREREQUISITE_OF":
            out["hands_to" if src == rid else "receives_from"].add(show(other))
        elif kind == "RELATED_TO":
            out["works_beside"].add(show(other))
        elif kind == "RETURNS_TO":
            out["returns_to" if src == rid else "receives_returns_from"].add(show(other))
    return {k: sorted(v) for k, v in out.items() if v}


def build_payload(roles: list[dict]) -> dict:
    """그래프 노드 목록 → 스냅샷 payload. 순수 함수다(테스트가 네트워크 없이 부른다).

    `prompts/get` 도 이 함수를 지난다 — 라이브 노드 하나를 스냅샷과 **같은 모양**으로
    접어야 렌더러가 껍데기와 같은 바이트를 낸다. 그것이 W2 의 종료 시험이다.
    `works_with` 는 노드에 없고 호출자가 엣지에서 계산해 붙인다(:func:`works_with`)."""
    out = []
    for node in sorted(roles, key=lambda n: n["id"]):
        rid = node["id"]
        if not rid.startswith(ID_PREFIX):
            continue
        entry = {
            "id": rid,
            "name": rid.split(":", 1)[1],
            "label": node.get("label") or node.get("title") or "",
            "domain": node.get("domain") or "",
            "tags": sorted(node.get("tags") or []),
            "props": _order(node.get("props") or {}),
        }
        if node.get("works_with"):
            entry["works_with"] = _order(node["works_with"])
        out.append(entry)
    return {"note": _NOTE, "topics": list(TOPICS), "roles": out}


# ── 껍데기 ────────────────────────────────────────────────────────────────────

def _bullets(items) -> str:
    def show(item):
        if isinstance(item, dict) and set(item) == {"action", "reason"}:
            return f"{item['action']}: {item['reason']}"
        return str(item)
    return "\n".join(f"- {show(i)}" for i in items) if items else "- (none)"


def _gate_bullets(items) -> str:
    if not items:
        return "- (none)"
    # 문자열 목록의 기존 바이트를 보존하고, 구조 조건은 키를 숨기지 않고 싣는다.
    return "\n".join("- " + (json.dumps(item, ensure_ascii=False, sort_keys=True,
                        separators=(",", ":")) if isinstance(item, dict) else str(item))
                       for item in items)


def render_shell(role: dict, *, compact: bool = False) -> str:
    """스냅샷 항목 → 역할 껍데기(`agents/shells/<name>.md`) 본문. 결정론이다 — 같은 입력이면 같은
    바이트가 나와야 `--check` 가 성립하고, `prompts/get` 이 껍데기와 같은 계약을
    낸다고 말할 수 있다."""
    props = role.get("props") or {}
    rid, name = role["id"], role["name"]
    if compact:
        lines = [f"# {role.get('label') or name}", rid,
                 f"Tier {props.get('tier', '')}, rung {props.get('rung', '')}",
                 "", "## Mission", str(props.get("mission") or "")]
        for key in ("gates", "never", "person_only"):
            renderer = _gate_bullets if key == "gates" else _bullets
            lines += ["", "## " + key.replace("_", " ").capitalize(), renderer(props.get(key))]
        if "never_checks" in props:
            lines += ["", "## Machine checks for Never", _gate_bullets(props["never_checks"])]
        if role.get("works_with"):
            lines += ["", "## Works with"]
            for direction, peers in role["works_with"].items():
                lines.append(f"- {direction}: {', '.join(peers)}")
        return "\n".join(lines) + "\n"
    rung = props.get("rung", "")
    mission = " ".join((props.get("mission") or role.get("label") or "").split())
    reads = "\n".join(f"{i}. {d}" for i, d in enumerate(props.get("reads") or [], 1))
    # 하네스가 역할을 고를 때 읽는 것은 description 한 줄이다. 직무명과 팀을 앞에 둔다.
    job, team = props.get("job_title"), props.get("team")
    summary = f"{job} ({team}). {mission}" if job and team else mission

    # 프런트매터. 금지는 `tools`(허용목록)가 아니라 `disallowedTools`(거부목록)로 낸다.
    # 허용목록이면 MCP 도구를 서버 이름으로 일일이 대야 하는데, 그 이름은 기기 설정이고
    # 이 리포에 `.mcp.json` 이 없다. 그러면 역할이 자기 정의를 읽는 부팅 두 호출이
    # 죽는다. 거부목록은 상속 풀에서 빼기만 하므로 그 결합이 없다.
    # 정본: [[record:an-agent-tool-allowlist-cannot-hold-mcp-here-so-the-denylist-does]]
    front = ["---", f"name: {name}", f"description: {summary}",
             f"model: {RUNG_TO_MODEL.get(rung, '')}"]
    # `isolation: worktree` 는 하네스가 그 역할에 **리포 사본 하나**를 따로 준다. 값은
    # 역할 노드가 정하고 여기는 옮기기만 한다 — 어느 역할이 격리되는지는 모델 사다리와
    # 같이 그래프의 판단이다. 값 문자열을 검사하지 않는 것도 같은 이유다: 하네스가 아는
    # 낱말이 늘면 노드만 고치면 된다.
    # 정본: [[record:worktree-isolation-makes-one-branch-per-package-physical]]
    if props.get("isolation"):
        front.append(f"isolation: {props['isolation']}")
    if props.get("disallowed_tools"):
        front.append("disallowedTools: " + ", ".join(props["disallowed_tools"]))
    body = front + [
        "---",
        "",
        "<!-- generated by scripts/agents_sync.py --gen from agents/roles.json. Do not hand",
        f"     edit; the definition is canonical in the graph at {rid}. -->",
        "",
        f"# {role.get('label') or name}",
        "",
        f"Tier {props.get('tier', '')}, rung {rung}"
        + (f", delegating at {props['delegate_rung']}" if props.get("delegate_rung") else "")
        + ".",
    ]
    if team:
        body += ["", f"Team {team}, {props.get('team_role') or 'member'}."]
    body += [
        "",
        "## Read the definition first",
        "",
        "This file is a pointer. The role is defined in the graph, and two calls read it:",
        "",
        "```",
        f"vinc_graph      seed_id={rid} depth=1",
        f"vinc_neighbors  node={rid}",
        "```",
        "",
        "Two calls rather than one, because neighbors does not return props and the call that",
        "does is heavy. What follows is a snapshot, and the graph wins where they differ.",
        "",
        "## Mission",
        "",
        mission or "(none)",
        "",
        "## Surface",
        "",
        f"Repositories: {', '.join(props.get('repos') or []) or '(none)'}",
        "",
        _bullets(props.get("paths")),
        "",
        "## Read before the first edit, in this order",
        "",
        reads or "1. (none)",
        "",
        "## Gates that must pass before the pull request",
        "",
        _gate_bullets(props.get("gates")),
    ]
    if props.get("test_command"):
        body += ["", "Test command:", "", "```", props["test_command"], "```"]
    together = role.get("works_with") or {}
    if together:
        body += ["", "## Works with", ""]
        for key, head in (("hands_to", "Hands off to"), ("receives_from", "Receives from"),
                          ("works_beside", "Works beside"), ("returns_to", "Returns to"),
                          ("receives_returns_from", "Receives rejected packages from")):
            if together.get(key):
                body.append(f"- {head}: {', '.join(together[key])}")
    if props.get("tools"):
        # 선언이지 강제가 아니다. 허용목록(`tools:`)은 MCP 서버 이름이 기기 설정이라
        # 역할의 부팅 호출까지 잘라 버리므로 거부목록만 프런트매터에 낸다.
        body += ["", "## Tools and MCP servers", "", _bullets(props["tools"]), "",
                 "The harness enforces only the denylist in the front matter; this list is the",
                 "job's declared kit. Before accepting a package, confirm each server named here",
                 "is reachable in this session. If one is missing, return the package and name",
                 "the missing server instead of substituting another tool. Reasoning:",
                 "[[decision:roster-shells-carry-a-denylist-not-an-allowlist]]."]
    body += [
        "",
        "## Never",
        "",
        _bullets(props.get("never")),
        "",
        "## Only a person does this",
        "",
        _bullets(props.get("person_only")),
    ]
    if "never_checks" in props:
        body += ["", "## Machine checks for never", "", _gate_bullets(props["never_checks"])]
    # `pre_merge_check` 가 맨 앞인 이유: 이것만 서술이 아니라 **행위 직전에 돌릴
    # 명령**이다. 적어 두는 것은 함정을 막지 못하고 그 자리의 검사가 막는다
    # ([[record:writing-a-trap-down-does-not-stop-it-a-check-does]]).
    for key in ("pre_merge_check", "speaks_to_the_person", "verify", "trap_note",
                "engine_note", "baseline_note", "claim_note", "tool_note",
                "enforcement_note", "session_close"):
        if props.get(key):
            body += ["", f"## {key.replace('_', ' ').capitalize()}", "", props[key]]
    if props.get("writes_graph"):
        body += ["", "## Writes to the graph", "", _bullets(props["writes_graph"])]
    body += [
        "",
        "## Output contract",
        "",
        "A sentence of the form checked, verified, confirmed, present, absent, or returns X",
        "carries the tool call that produced it: the query as it was run and its first result,",
        "or the call id. A statement without one is reported in the word assumed.",
        "",
        "This is not a style rule. A session reported a findability check as having been asked",
        "in Korean when it had been asked in English, and nothing in the output told the two",
        "apart. Vinc cannot make an agent run a query it says it ran; this contract refuses the",
        "sentence instead. Reasoning: [[vinc.ops.graph-claim-decay]] section 7.4.",
        "",
        "Escalation is one rung up, per decision:agent-model-ladder. The verify tier does not",
        "escalate; it returns the package to its author instead.",
        "",
    ]
    return "\n".join(body)


def render_community_export(snapshot: dict, source: dict, format: str, *, pack_encoder=None) -> dict:
    """고정된 공유 버전을 같은 역할 렌더러로 낸다. 내용은 지시 권한이나 도구 부여가 아니다."""
    import base64
    import hashlib
    from store.canon import canonical_json as canonical
    if format not in {"claude", "gpt", "skill", "vincpack"}:
        raise ValueError("invalid_agent_export_format")
    role = snapshot["role"]
    attribution = "Deleted author" if source["author"]["deleted"] else source["author"]["handle"] or "Author"
    prefix = (f"# {role['label']}\n\nSource: {source['url']}\nVersion: {source['version']}\n"
              f"Snapshot SHA256: {source['hash']}\nLicense: {snapshot['license']}\nAuthor: {attribution}\n\n"
              "This export does not execute or activate the role, or grant tools. Review before adopting it.\n\n")
    full = (prefix + render_shell(role) + "\n## Authored instruction\n\n" + snapshot["prompt"]
            + "\n\n## Complete immutable snapshot\n\n" + _fence(canonical(snapshot)) + "\n")
    name = role["name"]
    if format == "vincpack":
        if not callable(pack_encoder):
            raise ValueError("agent_pack_encoder_required")
        props = {**role["props"], "active": False, "status": "proposed",
                 "community_source": source, "shared_snapshot": snapshot}
        pack = {"vinc_pack": agent_export_contract.AGENT_PACK_VERSION,
                "kind": agent_export_contract.AGENT_PACK_KIND, "manifest": {"agent_source": source,
                "license": snapshot["license"], "status": "proposed",
                "required_reader": agent_export_contract.required_reader()},
                "fragment": {"nodes": [{"id": role["id"], "type": "concept", "title": role["label"],
                "one_liner": role["props"]["mission"], "domain": "agent", "tags": role["tags"], "props": props}], "edges": []}}
        content = pack_encoder(json.loads(canonical(pack)))
        filename, mime, encoding = name + ".vincpack", "application/octet-stream", "base64"
    else:
        if format == "skill":
            # 파일 이름이 다른 번들도 같은 계약 전문을 보존한다. 하네스 설치는 하지 않는다.
            full = (f"---\nname: {name}\ndescription: {json.dumps(role['props']['mission'], ensure_ascii=False)}\n---\n\n" + full)
        content = full.encode("utf-8")
        filename = "SKILL.md" if format == "skill" else name + "." + format + ".md"
        mime, encoding = "text/markdown; charset=utf-8", "utf8"
    return {"executed": True, "content": base64.b64encode(content).decode("ascii") if encoding == "base64" else content.decode("utf-8"),
            "encoding": encoding, "filename": filename, "mime": mime, "hash": source["hash"],
            "content_hash": hashlib.sha256(content).hexdigest(), "version": source["version"], "format": format,
            **({"pack_version": agent_export_contract.AGENT_PACK_VERSION,
                "required_reader": agent_export_contract.required_reader(),
                "legacy_import_compatible": False} if format == "vincpack" else {})}


