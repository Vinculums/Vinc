def render_codeowners(teams: dict) -> str:
    """teams.json → CODEOWNERS 본문. 결정론이다(`--check` 가 바이트를 대조한다).

    GitHub 는 **뒤의 줄이 이긴다.** 그래서 순서가 곧 우선순위다: 팀의 `paths` 를
    teams.json 에 적힌 팀 순서대로 쓰고, `shared` 를 맨 뒤에 둬 공동 소유가 팀 줄을
    덮게 한다. 팀 줄 사이의 우선순위는 **경로 깊이**로 잡는다(짧은 접두가 먼저, 긴
    경로가 뒤) — `scripts/` 가 core 에 있고 `scripts/gate_*.py` 가 platform 에 있을 때
    팀 순서와 무관하게 구체적인 쪽이 이겨야 하기 때문이다.
    """
    lines = [
        f"# {GENERATED_MARK} — from agents/teams.json. 손으로 고치지 말 것: --check 가 대조한다.",
        "# 뒤의 줄이 이긴다. 짧은 접두가 먼저, 구체적인 경로가 뒤, 공동 소유가 맨 뒤.",
        "",
    ]
    rows: list[tuple[int, str, str, str]] = []
    for order, (name, t) in enumerate(teams["teams"].items()):
        for p in t.get("paths", []):
            rows.append((p.rstrip("/").count("/"), order, p, t["github"]))
    for depth, _order, p, handle in sorted(rows):
        anchored = p if p.startswith("/") else "/" + p
        lines.append(f"{anchored:<48} {handle}")
    shared = teams.get("shared", {}).get("paths", {})
    if shared:
        lines.append("")
        lines.append("# 공동 소유 — 두 팀이 같이 리뷰한다.")
        handle = {name: t["github"] for name, t in teams["teams"].items()}
        for p in sorted(shared, key=lambda s: (s.count("/"), s)):
            owners = " ".join(handle[n] for n in shared[p])
            lines.append(f"{'/' + p:<48} {owners}")
    return "\n".join(lines) + "\n"

