def cmd_pull() -> int:
    """**여기만 네트워크를 쓴다** — `refresh_graph_refs.py` 와 같은 자리, 같은 이유."""
    from vinc_mcp import remote

    # 역할 발견은 UI와 같은 서버 판정을 쓴다. 빈 후보 페이지도 이어 읽는다.
    found = {}
    offset = 0
    while True:
        page = remote.call("vinc_role", {"limit": 100, "offset": offset})
        if page.get("isError") or not page.get("executed") or not isinstance(page.get("roles"), list):
            raise SystemExit("[agents] role roster unavailable")
        for row in page["roles"]:
            found[str(row["id"])] = row
        next_offset = page.get("next_offset")
        if next_offset is None:
            break
        if isinstance(next_offset, bool) or not isinstance(next_offset, int) or next_offset <= offset:
            raise SystemExit("[agents] invalid role roster pagination")
        offset = next_offset
    fetched = {}
    for rid in sorted(found):
        got = remote.call("vinc_graph", {"seed_id": rid, "depth": 1})
        if got.get("isError") or not got.get("found"):
            # 상한 초과 같은 도구 오류는 `text` 에 온다 — `error` 만 보면 None 이 찍혀
            # 왜 죽었는지 알 수 없다(2026-09-05 실측).
            raise SystemExit(f"[agents] {rid} 조회 실패: "
                             f"{got.get('error') or got.get('text') or got}")
        node = next((n for n in got.get("nodes", []) if n.get("id") == rid), None)
        if node is None:
            # 고립 노드가 빈 필드로 보고되던 전례가 있다
            # ([[record:isolated-seed-read-back-reported-empty-fields]]). 조용히 빈
            # 역할을 쓰느니 여기서 죽는 편이 낫다.
            raise SystemExit(f"[agents] {rid} 가 자기 응답의 nodes 에 없다")
        fetched[rid] = (got, node)

    # 모델 없는 역할(태그 model-free, CI 에서 도는 스크립트)은 하위 에이전트가 아니므로
    # 껍데기를 만들지 않는다. 협업 상대에서도 빠진다.
    for rid, (_, node) in list(fetched.items()):
        if MODEL_FREE_TAG in (node.get("tags") or []):
            del fetched[rid], found[rid]
            print(f"[agents] {rid}: model-free, 껍데기 없음")
    ids = sorted(fetched)
    if not ids:
        raise SystemExit("[agents] no active roles in this space")
    print(f"[agents] 역할 {len(ids)}개")

    roles = []
    for rid in ids:
        got, node = fetched[rid]
        # 계약 전문은 기존 그래프 응답에서 보존한다. 협업 상대는 발견된 활성 역할만 쓴다.
        peers = [n for n in got.get("nodes") or [] if n.get("id") in found]
        edges = [e for e in got.get("edges") or []
                 if e.get("source") in found and e.get("target") in found]
        roles.append(dict(node, works_with=works_with(rid, peers, edges)))

    write_snapshot(build_payload(roles))
    print(f"[agents] 썼다: {SNAPSHOT.relative_to(ROOT)} — git diff 가 그래프가 앞서간 만큼이다")
    return 0


def cmd_pull_ladder() -> int:
    """사다리 결정 → `agents/model-ladder.json`. 역할 노드가 아니지만 `--pull` 이 같은 주기로 이어 부른다."""
    from vinc_mcp import remote

    got = remote.call("vinc_node", {"node_id": LADDER_ID})
    if got.get("isError") or not got.get("found") or not isinstance(got.get("node"), dict):
        raise SystemExit(f"[agents] {LADDER_ID} 조회 실패: {got.get('error') or got.get('text') or got}")
    write_ladder(ladder_payload(got["node"]))
    print(f"[agents] 썼다: {LADDER.relative_to(ROOT)} — git diff 가 사다리가 바뀐 만큼이다")
    return 0


def cmd_gen() -> int:
    snap = read_snapshot()
    SHELL_DIR.mkdir(parents=True, exist_ok=True)
    for role in snap["roles"]:
        fp = shell_path(role)
        with io.open(fp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_shell(role))
        print(f"[agents] {fp.relative_to(ROOT)}")
    print(f"[agents] 껍데기 {len(snap['roles'])}개 생성")
    _write_if_changed(STOP_HOOK_SNIPPET, render_stop_hook(snap))
    print(f"[agents] {STOP_HOOK_SNIPPET.relative_to(ROOT)}")
    CODEOWNERS.parent.mkdir(parents=True, exist_ok=True)
    with io.open(CODEOWNERS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_codeowners(read_teams()))
    print(f"[agents] {CODEOWNERS.relative_to(ROOT)}")
    return 0


def cmd_check() -> int:
    snap = read_snapshot()
    bad = 0
    expected = set()
    for role in snap["roles"]:
        fp = shell_path(role)
        expected.add(fp.resolve())
        if not fp.exists():
            print(f"[MISSING] {fp.relative_to(ROOT)} — --gen 을 돌려야 한다")
            bad += 1
            continue
        if fp.read_text(encoding="utf-8") != render_shell(role):
            print(f"[TAMPERED] {fp.relative_to(ROOT)} — 스냅샷에서 재생성한 것과 다르다. "
                  f"생성물이라 여기서 고치면 안 된다: 그래프의 {role['id']} 를 고치고 "
                  f"--pull → --gen")
            bad += 1
        else:
            print(f"[OK] {fp.relative_to(ROOT)}")

    if SHELL_DIR.exists():
        for fp in sorted(SHELL_DIR.glob("*.md")):
            if fp.resolve() not in expected:
                print(f"[UNLISTED] {fp.relative_to(ROOT)} 가 스냅샷에 없다 — 역할이 그래프에서 "
                      f"사라졌으면 파일도 지우고, 아니면 --pull 로 스냅샷을 갱신하라")
                bad += 1

    if not STOP_HOOK_SNIPPET.exists():
        print(f"[MISSING] {STOP_HOOK_SNIPPET.relative_to(ROOT)} — --gen 을 돌려야 한다")
        bad += 1
    elif STOP_HOOK_SNIPPET.read_text(encoding="utf-8") != render_stop_hook(snap):
        print(f"[TAMPERED] {STOP_HOOK_SNIPPET.relative_to(ROOT)} — 스냅샷에서 재생성한 것과 다르다. "
              f"생성물이라 여기서 고치면 안 된다: --gen")
        bad += 1
    else:
        print(f"[OK] {STOP_HOOK_SNIPPET.relative_to(ROOT)}")

    if not CODEOWNERS.exists():
        print(f"[MISSING] {CODEOWNERS.relative_to(ROOT)} — --gen 을 돌려야 한다")
        bad += 1
    elif CODEOWNERS.read_text(encoding="utf-8") != render_codeowners(read_teams()):
        print(f"[TAMPERED] {CODEOWNERS.relative_to(ROOT)} — teams.json 에서 재생성한 것과 "
              f"다르다. 생성물이라 여기서 고치면 안 된다: agents/teams.json 을 고치고 --gen")
        bad += 1
    else:
        print(f"[OK] {CODEOWNERS.relative_to(ROOT)}")

    docs = _manifest_docs()
    if docs is None:
        print("[SKIP] scripts/graph-refs.json 이 없어 reads 검사를 건너뛴다")
    else:
        for name, doc_id in dangling_reads(snap, docs):
            print(f"[DANGLING] {name} 의 reads 가 매니페스트에 없는 문서를 가리킨다: "
                  f"{doc_id} — 문서가 개명·삭제됐거나 매니페스트가 낡았다. "
                  f"scripts/refresh_graph_refs.py 를 돌려 같은 커밋에 넣는다")
            bad += 1

    print(f"\n{'역할 껍데기 이상 없음' if not bad else f'문제 {bad}건'}")
    return 1 if bad else 0


