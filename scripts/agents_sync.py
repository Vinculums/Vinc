def main_checkout() -> Path:
    """이 트리가 속한 리포의 **메인 체크아웃**. `ROOT` 가 아니다 — worktree(`_wt/x`,
    `Vinc/.claude/worktrees/x`)에서 돌리면 `ROOT.parent` 는 워크스페이스 루트가 아니다.
    git 공용 디렉터리(`Vinc/.git`)의 부모가 어느 worktree 에서 물어도 같은 답이다."""
    common = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "--path-format=absolute", "--git-common-dir"],
        capture_output=True, text=True, check=True).stdout.strip()
    return Path(common).resolve().parent


def _write_if_changed(fp: Path, text: str) -> bool:
    if fp.exists() and fp.read_text(encoding="utf-8") == text:
        return False
    fp.parent.mkdir(parents=True, exist_ok=True)
    with io.open(fp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return True


def install(root: Path, repo: Path, python: str) -> list[str]:
    """`<root>/.claude` 에 껍데기·worktree 훅·훅 설정을 넣고, 바꾼 것의 목록을 돌려준다.

    몇 번을 돌려도 같다: 내용이 같으면 쓰지 않으므로 두 번째 실행은 빈 목록이다.
    `.claude` 안에서 만지는 것은 셋뿐이다 — `agents/` 의 생성 껍데기, `hooks/` 의 훅
    파일 하나, `settings.json` 의 `hooks.WorktreeCreate`·`hooks.WorktreeRemove`·
    `hooks.SubagentStop` 세 키. settings.json 의 나머지 키와 그 밖의 파일(launch.json·
    settings.local.json 등)은 읽지도 않는다. worktree 두 키는 통째로 이것으로 갈아 끼운다:
    WorktreeCreate 는 경로 하나를 돌려주는 계약이라 둘이 공존할 수 없다. SubagentStop 은
    다른 훅 묶음을 남기고 이 훅 파일의 묶음만 갈아 끼운다.

    훅이 있는 이유: dev 역할은 `isolation: worktree` 를 싣고, 루트는 git 리포가 아니라서
    훅 없이는 하네스가 그 역할을 거절한다(`scripts/worktree_hook.py` 머리말)."""
    snap = read_snapshot()
    claude = root / ".claude"
    changed: list[str] = []

    agents = claude / "agents"
    wanted = set()
    for role in snap["roles"]:
        fp = agents / f"{role['name']}.md"
        wanted.add(fp.name)
        if _write_if_changed(fp, render_shell(role)):
            changed.append(f"agents/{fp.name}")
    for fp in sorted(agents.glob("*.md")):
        if fp.name not in wanted and GENERATED_MARK in fp.read_text(encoding="utf-8", errors="replace"):
            fp.unlink()  # 그래프에서 사라진 역할. 남기면 그것이 곧 낡은 로스터다
            changed.append(f"agents/{fp.name} (removed)")

    hook = claude / "hooks" / HOOK_SRC.name
    if _write_if_changed(hook, HOOK_SRC.read_text(encoding="utf-8")):
        changed.append(f"hooks/{hook.name}")

    settings_fp = claude / "settings.json"
    settings = json.loads(settings_fp.read_text(encoding="utf-8")) if settings_fp.exists() else {}
    before = copy.deepcopy(settings)
    tail = ["--repo", str(repo), "--into", str(root / "_wt")]
    hooks = settings.setdefault("hooks", {})
    for event, verb in HOOK_EVENTS:
        # 실행 형식(args)이라 셸이 없다 — 경로 따옴표 문제가 없고 윈도에서 Git Bash 를
        # 안 거친다. `-I` 는 전역 PYTHONHOME/PYTHONPATH 를 무시하게 하고(CLAUDE.md §5),
        # `-X utf8` 은 파이프로 나가는 stdout 을 로캘(cp949)이 아니라 UTF-8 로 쓰게 한다 —
        # 하네스가 그 줄을 경로로 읽으므로 비ASCII 경로가 깨지면 생성이 실패한다.
        ours = {"hooks": [{"type": "command", "command": python,
                           "args": ["-I", "-X", "utf8", str(hook), verb, *tail]}]}
        # SubagentStop 은 남의 훅과 공존한다: 이 훅 파일을 부르는 묶음만 갈아 끼운다.
        others = [g for g in hooks.get(event, []) if event == "SubagentStop"
                  and not any(str(hook) in (h.get("args") or []) for h in g.get("hooks", []))]
        hooks[event] = [*others, ours]
    if settings != before:
        _write_if_changed(settings_fp, json.dumps(settings, ensure_ascii=False, indent=2) + "\n")
        changed.append(f"settings.json (hooks.{', hooks.'.join(e for e, _ in HOOK_EVENTS)})")
    return changed


def cmd_install() -> int:
    repo = main_checkout()
    root = repo.parent
    changed = install(root, repo, sys.executable)
    for item in changed:
        print(f"[agents] 썼다: {root / '.claude' / item}")
    print(f"[agents] {root / '.claude'}: "
          + (f"{len(changed)}건 바꿨다" if changed else "이미 같다, 쓴 것 없음"))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="agent roster: graph to snapshot to shells")
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--pull", action="store_true",
                       help="그래프에서 스냅샷을 다시 만든다(토큰 필요)")
    group.add_argument("--gen", action="store_true", help="스냅샷에서 껍데기를 생성한다")
    group.add_argument("--check", action="store_true",
                       help="껍데기가 스냅샷과 같은가(오프라인)")
    group.add_argument("--install", action="store_true",
                       help="워크스페이스 루트(메인 체크아웃의 부모)의 .claude 에 설치한다")
    args = ap.parse_args(argv)
    if args.pull:
        return cmd_pull() or cmd_pull_ladder()
    if args.gen:
        return cmd_gen()
    if args.install:
        return cmd_install()
    return cmd_check()


if __name__ == "__main__":
    raise SystemExit(main())
