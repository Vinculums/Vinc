# -*- coding: utf-8 -*-
"""push_ssot.py — Claude Design 으로 보낼 **토큰 한 파일**을 게이트 걸고 빌드한다.

왜 `/ds-push` 를 그대로 안 쓰는가. 그 스킬의 직접 경로는 스스로 밝히듯 **tokens-only
허브**용이라 `styles.css` 를 `@import "./tokens/tokens.css"` 한 줄짜리로 갈아치운다.
Vinc 의 Claude Design 프로젝트는 tokens-only 가 아니다 — 컴포넌트 40여 개 · 템플릿 3 ·
ui_kits 2 · 가이드라인 카드 23장이 있고, `tokens/` 6개 중 둘은 **허브가 만들 수 없는
것**을 담는다:

  tokens/fonts.css   @font-face 6개(자체 호스팅 Pretendard·JetBrains Mono)
  tokens/base.css    리셋(box-sizing · body · ::selection · :focus-visible · accent-color)

생성기(`render_css`)는 `--font-*` 이름 스택만 내지 @font-face 를 못 만들고, 리셋은
애초에 토큰 생성기의 소관이 아니다. 그러니 한 파일로 합치면 그 둘을 잃는다.

그래서 경로를 가른다. 허브 출력은 **`tokens/ssot.css`** 한 곳으로만 가고, 프로젝트의
`styles.css` 는 그것을 **마지막에** import 한다(→ 값은 언제나 SSoT 가 이긴다).
결과적으로 푸시가 건드리는 파일은 하나뿐이라 카드·컴포넌트·템플릿은 사정권 밖이다.

    python -X utf8 scripts/design/push_ssot.py            # 게이트 + 빌드
    python -X utf8 scripts/design/push_ssot.py --setup    # 최초 1회: styles.css 도 함께 낸다

빌드 산출물은 `scripts/design/out/claude-design/`(커밋하지 않는다)이고, **업로드는 이 스크립트가 하지 않는다** —
DesignSync 는 에이전트의 도구다. 스크립트는 마지막에 그대로 쓸 수 있는 finalize_plan
인자를 찍어 준다. exit 0 = 업로드해도 좋음 · 2 = 게이트 BLOCK(업로드 금지) · 3 = 오류.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HUB = Path(__file__).resolve().parent
OUT = HUB / "out" / "claude-design"
sys.path.insert(0, str(HUB))
import build_tokens  # noqa: E402

#: 사이트와 같은 본문(모션 포함)을 스냅샷에서 바로 만들어 보낸다. 모션이 빠진 파일을 보내면
#: Claude Design 은 곡선도 시간도 없이 그린다. 근거: [[record:claude-design-tokens-frozen-at-2026-08-08]]
SITE_CSS = "site-tokens.css"

#: 프로젝트 `styles.css` 의 정본 형태. 손으로 유지하는 6개는 그대로 두고 허브 산출물을
#: **맨 끝에** 얹는다 — 뒤에 오는 :root 선언이 이기므로 값의 정본이 항상 SSoT 가 된다.
#: base.css 가 뒤에 와도 상관없다: 그건 var() 로 **쓰기만** 하고 정의하지 않는다.
STYLES = """/* Vinc "Signal" design system — global entry point.
   Consumers link this one file. Imports only; no rules live here.

   Order matters. The six hand-authored files below carry what the token SSoT cannot
   generate — @font-face for the self-hosted faces (fonts.css) and the base reset
   (base.css); the rest are this project's own split of the same values. `tokens/ssot.css`
   is generated by Vinc/scripts/design/build_tokens.py from the token snapshot and comes LAST, so
   for any value both define, the SSoT wins. Do not hand-edit tokens/ssot.css. */
@import url("tokens/fonts.css");
@import url("tokens/colors.css");
@import url("tokens/typography.css");
@import url("tokens/spacing.css");
@import url("tokens/depth.css");
@import url("tokens/base.css");
@import url("tokens/ssot.css");
"""


def _plugin_root() -> Path:
    env = os.environ.get("CLAUDE_PLUGIN_ROOT")
    if env:
        return Path(env)
    base = Path.home() / ".claude" / "plugins" / "cache" / "lime-design" / "lime-design"
    return sorted(base.iterdir())[-1]


def main() -> int:
    ap = argparse.ArgumentParser(description="Claude Design 용 토큰 파일 게이트+빌드")
    ap.add_argument("--setup", action="store_true",
                    help="최초 1회 — styles.css 도 함께 빌드(@import 한 줄 추가)")
    args = ap.parse_args()

    tokens = build_tokens.load()
    css_text = build_tokens.outputs(tokens)[SITE_CSS]
    # 모션이 빠진 파일을 보내는 것이 이 스크립트의 실제 고장이었다. 조용히 통과시키지 않는다.
    missing = [k for k in ("--ease-out", "--dur-base") if k not in css_text]
    if missing:
        print(f"[BLOCK] 모션 토큰이 없다({', '.join(missing)}) — 스냅샷의 motion 묶음을 볼 것",
              file=sys.stderr)
        return 2

    # 검증기는 DTCG 두 층만 읽는다. 테넌트 칸은 떼고 임시 파일로 넘긴다.
    with tempfile.TemporaryDirectory() as tmp:
        ssot = Path(tmp) / "design-tokens.json"
        ssot.write_text(json.dumps({k: v for k, v in tokens.items() if k != "tenants"},
                                   ensure_ascii=False), encoding="utf-8")
        gate = subprocess.run(
            [sys.executable, "-X", "utf8", str(_plugin_root() / "scripts" / "validate_design.py"),
             "--tokens", str(ssot), "--profile", str(HUB / "design.profile.yml"),
             "--out", tmp, "--format", "json"],
            capture_output=True, text=True, encoding="utf-8", cwd=HUB)
    if gate.returncode == 3:
        print(f"[ERROR] 게이트 엔진 실패:\n{gate.stderr}", file=sys.stderr)
        return 3
    try:
        verdict = json.loads(gate.stdout)
    except Exception:
        print(f"[ERROR] 게이트 출력 파싱 실패:\n{gate.stdout[:400]}", file=sys.stderr)
        return 3
    print(f"게이트: {verdict['status']} "
          f"(BLOCK {verdict['block_count']} · FIX {verdict['fix_count']} · INFO {verdict['info_count']})")
    if verdict["block_count"]:
        for f in verdict["findings"]:
            if f["severity"] == "BLOCK":
                print(f"  [BLOCK] {f['id']}: {f['found']}", file=sys.stderr)
        print("업로드 금지 — fail-closed", file=sys.stderr)
        return 2

    (OUT / "tokens").mkdir(parents=True, exist_ok=True)
    (OUT / "tokens" / "ssot.css").write_text(css_text, encoding="utf-8", newline="")
    writes = ["tokens/ssot.css"]
    if args.setup:
        (OUT / "styles.css").write_text(STYLES, encoding="utf-8", newline="")
        writes.insert(0, "styles.css")

    print(f"\n빌드 완료 → {OUT}")
    for w in writes:
        print(f"  {w}")
    print("\nDesignSync finalize_plan 인자:")
    print(json.dumps({"writes": writes, "localDir": str(OUT)}, ensure_ascii=False, indent=2))
    print("\n⚠ 이 스크립트는 업로드하지 않는다. writes 는 위 목록**만**이어야 한다 — "
          "guidelines/·components/·templates/·assets/ 가 계획에 들어가면 그건 사고다.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
